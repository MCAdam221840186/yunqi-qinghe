function hasMeaningfulText(value) {
  if (typeof value !== "string") return false;
  const normalized = value
    .replace(/\s+/gu, "")
    .replace(/[，。！？、；：,.!?;:'"“”‘’（）()【】\[\]]/gu, "");
  return normalized !== "" && normalized !== "无" && normalized !== "没有";
}

function excerptForNote(value, maximumLength = 52) {
  const normalized = value
    .replace(/\s+/gu, " ")
    .trim()
    .replace(/[，。！？；：,.!?;:]+$/u, "");
  return normalized.length <= maximumLength
    ? normalized
    : `${normalized.slice(0, maximumLength)}…`;
}

function noteForDiary(child, diary) {
  if (diary.kind === "structured") {
    const learned = [diary.fields.learned, diary.fields.happiest]
      .find(hasMeaningfulText);
    const message = hasMeaningfulText(diary.fields.message)
      ? diary.fields.message
      : "";
    if (learned && message && learned !== message) {
      return `${child.displayName}先写下“${excerptForNote(learned)}”，又把“${excerptForNote(message)}”留给明天的自己。`;
    }
    if (learned || message) {
      return `${child.displayName}把“${excerptForNote(learned || message)}”记在卡上，留下当天最直接的感受。`;
    }
    return `${child.displayName}在这张卡的三个栏目中都写下“无”，页面仍作为完整档案保留。`;
  }
  const childText = diary.body.split("\n\n老师：")[0].replace(/^孩子：/, "");
  const excerpt = excerptForNote(childText, 48);
  return `${child.displayName}在自由书写中回望当天体验：“${excerpt}”`;
}

const children = roster.map((child, offset) => {
  const meta = storyMeta[offset];
  const featured = diaryByIndex.get(meta.featuredIndex);
  if (!featured || featured.childSlug !== child.slug) {
    throw new Error(`${child.slug} 的代表卡 ${meta.featuredIndex} 归属不一致`);
  }
  const highlightIndices = highlightIndicesByChild[offset];
  if (
    highlightIndices.length < 1 ||
    highlightIndices.length > 3 ||
    new Set(highlightIndices).size !== highlightIndices.length ||
    !highlightIndices.includes(meta.featuredIndex)
  ) {
    throw new Error(`${child.slug} 的人工成长节点必须唯一、包含代表卡且不超过3个`);
  }
  const selected = highlightIndices.map((sourceIndex) => {
    const diary = diaryByIndex.get(sourceIndex);
    if (!diary || diary.childSlug !== child.slug) {
      throw new Error(`${child.slug} 的成长节点 ${sourceIndex} 归属不一致`);
    }
    return diary;
  });
  const chronological = [...selected].sort(
    (left, right) => left.sessionOrder - right.sessionOrder || left.sourceIndex - right.sourceIndex,
  );
  if (selected.some((diary, index) => diary.slug !== chronological[index].slug)) {
    throw new Error(`${child.slug} 的人工成长节点未按时间顺序声明`);
  }
  return {
    ...child,
    story: {
      summary: meta.summary,
      featuredDiarySlug: featured.slug,
      highlights: selected.map((diary) => ({
        diarySlug: diary.slug,
        title: diary.title,
        note: diary.slug === featured.slug ? meta.note : noteForDiary(child, diary),
        ...(diary.slug === featured.slug ? { quote: meta.quote } : {}),
      })),
    },
  };
});

