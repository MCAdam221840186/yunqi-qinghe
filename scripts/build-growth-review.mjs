function sessionForIndex(index) {
  if (
    (index >= 61 && index <= 91) ||
    (index >= 119 && index <= 138) ||
    (index >= 140 && index <= 144) ||
    index === 148 ||
    index === 149
  ) return 1;
  if ((index >= 92 && index <= 112) || (index >= 114 && index <= 118) || index === 145) return 2;
  if ((index >= 37 && index <= 60) || index === 113 || index === 139 || index === 146 || index === 147 || (index >= 150 && index <= 161)) return 3;
  return 4;
}

function dateForRow(item, kind) {
  if (kind === "plain") {
    if (item.explicitDate) {
      const [year, month, day] = item.explicitDate.split("-").map(Number);
      return {
        dateLabel: `${year}年${month}月${day}日`,
        recordedOn: item.explicitDate,
        dateConfidence: "exact",
      };
    }
    return { dateLabel: "日期未填写", recordedOn: null, dateConfidence: "missing" };
  }
  if (item.index === 28) {
    return { dateLabel: "7月20日（原写7月18日后改）", recordedOn: null, dateConfidence: "uncertain" };
  }
  if (item.index === 147) {
    return { dateLabel: "2027月18日（原卡如此）", recordedOn: null, dateConfidence: "uncertain" };
  }
  const day = item.index <= 36 ? 20 : sessionForIndex(item.index) === 3 ? 18 : sessionForIndex(item.index) === 2 ? 17 : 16;
  return { dateLabel: `7月${day}日`, recordedOn: null, dateConfidence: "uncertain" };
}

